import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {chromium} from 'playwright';
const base='http://127.0.0.1:4318',dir='evidence/tianyuan-parity-v021/live';
await fs.mkdir(dir,{recursive:true});
const get=async key=>{const r=await fetch(base+'/api/'+key);assert.equal(r.status,200);return r.json();};
const baseline=JSON.parse(await fs.readFile('evidence/tianyuan-parity-v021/before-resume.json','utf8'));
assert.deepEqual({workspace:await get('workspace'),pro:await get('pro')},baseline);
const status=await get('status');assert.equal(status.version,'0.21.0');
const browser=await chromium.launch({channel:'msedge'}),errors=[],sources=[],pending=[],checks={};
try{
 const p=await browser.newPage({viewport:{width:1440,height:1000}});p.setDefaultTimeout(45000);
 p.on('pageerror',e=>errors.push(e.message));
 p.on('response',r=>{if(r.url().includes('/api/source-plus?'))pending.push((async()=>{const data=await r.json();sources.push({request:r.url(),status:r.status(),url:data.url,date:data.query?.date,kind:data.query?.kind,cache:data.cache,fetchedAt:data.fetchedAt,rawSha256:data.rawSha256,error:data.error});})());});
 await p.goto(base);await p.locator('nav').getByRole('button',{name:'数据与工具',exact:true}).click();
 await p.getByRole('button',{name:'巅峰玩家',exact:true}).click();
 await p.getByRole('combobox',{name:'玩家分路',exact:true}).count().catch(()=>0);
 await p.getByRole('table',{name:'上榜英雄分布'}).waitFor();
 checks.playerDistribution=await p.locator('.player-hero-distribution').innerText();
 await p.screenshot({path:dir+'/players.png'});
 await p.getByRole('button',{name:'全皮肤库',exact:true}).click();await p.getByLabel('搜索皮肤库',{exact:true}).fill('诸葛亮 星域');await p.locator('.plus-skin-card').click();
 await p.locator('.skin-comparison svg').waitFor();
 await p.locator('.skin-comparison fieldset input[type=checkbox]').first().check();
 assert.equal(await p.locator('.skin-comparison svg path').count(),2);
 checks.skinSelection=await p.getByRole('combobox',{name:'选择皮肤',exact:true}).inputValue();assert.equal(checks.skinSelection,'19006');
 await p.screenshot({path:dir+'/skin-comparison.png'});
 await p.setViewportSize({width:390,height:844});assert.ok(await p.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
 await p.screenshot({path:dir+'/skin-mobile.png'});await p.keyboard.press('Escape');await p.setViewportSize({width:1440,height:1000});
 await p.locator('nav').getByRole('button',{name:'阵容备战',exact:true}).click();await p.getByText('系列赛全局 BP · BO3 / BO5 / BO7 / BO9',{exact:true}).click();
 await p.locator('.series-server-save summary').click();await p.locator('.series-server-save').getByText(/本机访客/).waitFor();
 checks.serverSeriesRead=await p.locator('.series-server-save').innerText();
 await p.screenshot({path:dir+'/series-ready.png'});
 await Promise.all(pending);assert.deepEqual(errors,[]);
 const after={workspace:await get('workspace'),pro:await get('pro')};assert.deepEqual(after,baseline);
 const sha=createHash('sha256').update(JSON.stringify(after)).digest('hex');
 await fs.writeFile(dir+'/verification.json',JSON.stringify({at:new Date().toISOString(),version:status.version,checks,sources,errors,personalDataUnchanged:true,personalDataSha256:sha,pool:after.workspace.pool},null,2));
 console.log(JSON.stringify({version:status.version,sourceQueries:sources.length,errors,personalDataUnchanged:true,pool:after.workspace.pool}));
}finally{await browser.close();}
