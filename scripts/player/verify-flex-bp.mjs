import fs from 'node:fs/promises';
import { createHash } from 'node:crypto';
import assert from 'node:assert/strict';
import { chromium } from 'playwright';
const base='http://127.0.0.1:4318',dir='evidence/flex-bp-v019/live';
await fs.mkdir(dir,{recursive:true});
const read=async name=>{const response=await fetch(base+'/api/'+name);assert.ok(response.ok);return response.json();};
const before=JSON.parse(await fs.readFile('data/flex-bp-before/live.json','utf8'));
const status=await read('status');assert.equal(status.version,'0.19.0');
const browser=await chromium.launch({channel:'msedge'}),errors=[],checks={};
try{
  const page=await browser.newPage({viewport:{width:1440,height:1000}});page.on('pageerror',e=>errors.push(e.message));
  await page.goto(base);await page.locator('nav').getByRole('button',{name:'阵容备战',exact:true}).click();
  const panel=page.locator('.bp-rounds');await panel.getByRole('button',{name:'开始新演练',exact:true}).click();
  const pick=async name=>{await panel.getByRole('button',{name:'BP选择'+name,exact:true}).click();await panel.getByRole('button',{name:'确认本轮',exact:true}).click();};
  for(const name of ['廉颇','小乔','赵云','墨子','诸葛亮','孙尚香','刘禅'])await pick(name);
  const z=panel.getByRole('region',{name:'蓝方阵容'}).locator('.bp-pick-slot').filter({hasText:'诸葛亮'});
  checks.openFlex=await z.innerText();assert.match(checks.openFlex,/仍可摇摆/);
  await panel.locator('.bp-board').first().screenshot({path:dir+'/flex-open.png',animations:'disabled'});
  await pick('妲己');checks.afterMage=await z.innerText();assert.match(checks.afterMage,/当前推断：打野/);
  await panel.locator('.bp-board').first().screenshot({path:dir+'/resolved-desktop.png',animations:'disabled'});
  await panel.getByLabel('蓝方诸葛亮分路',{exact:true}).selectOption('中路');
  checks.manualSwap=await panel.getByLabel('蓝方妲己分路',{exact:true}).inputValue();assert.equal(checks.manualSwap,'打野');
  assert.equal(await panel.locator('.bp-role-warning').count(),1);
  await page.reload();await page.locator('nav').getByRole('button',{name:'阵容备战',exact:true}).click();
  assert.equal(await panel.getByLabel('蓝方诸葛亮分路',{exact:true}).inputValue(),'中路');
  await page.setViewportSize({width:390,height:844});
  await panel.locator('.bp-board').first().screenshot({path:dir+'/manual-swap-mobile.png',animations:'disabled'});
  checks.mobileOverflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);assert.equal(checks.mobileOverflow,false);
  await panel.getByRole('region',{name:'蓝方阵容'}).getByRole('button',{name:'本方全部恢复自动分路',exact:true}).click();
  await panel.getByRole('button',{name:'撤回一步',exact:true}).click();await pick('李白');
  checks.afterJungler=await z.innerText();assert.match(checks.afterJungler,/当前推断：中路/);
  checks.brokenImages=await panel.locator('.bp-board img').evaluateAll(xs=>xs.filter(x=>!x.complete||!x.naturalWidth).map(x=>x.src));assert.deepEqual(checks.brokenImages,[]);
  assert.deepEqual(errors,[]);
}finally{await browser.close();}
const data={workspace:await read('workspace'),pro:await read('pro')};
const hash=createHash('sha256').update(JSON.stringify(data)).digest('hex');assert.equal(hash,before.hash);
await fs.writeFile(dir+'/verification.json',JSON.stringify({at:new Date().toISOString(),status,checks,errors,personalDataPreserved:true,beforeHash:before.hash,afterHash:hash,zhaohuaizhenInPool:data.workspace.pool.some(h=>h.heroId===544)},null,2));
console.log(JSON.stringify({version:status.version,checks,personalDataPreserved:true,errors},null,2));
